import Foundation

/// Generates the statusline wrapper. Claude Code runs it on every statusline render with the session JSON on stdin.
/// It reads stdin once, saves only `rate_limits` plus a timestamp (atomically: temp file + `mv`), then feeds the same
/// input to the user's previous statusline command and prints its output. Every failure in the saving part is
/// swallowed, so the statusline itself never breaks. JSON tools: `jq` when present (macOS 15+ ships it), else
/// `/usr/bin/plutil`, which every macOS has. `python3` is avoided: on a Mac without developer tools it is a stub that
/// opens an install dialog.
public enum StatuslineScript {
    public static let marker = "# AImana statusline wrapper"

    public static func render(outputFile: URL, previousCommand: String?) -> String {
        """
        #!/bin/sh
        \(marker) — generated by AImana for Mac. Remove it from AImana › Settings › Uninstall.
        # Saves Claude Code's rate_limits for AImana, then runs your previous statusline unchanged.
        input=$(/bin/cat)
        out=\(shellQuote(outputFile.path))
        (
          rl=''
          if command -v jq >/dev/null 2>&1; then
            rl=$(printf '%s' "$input" | jq -c '.rate_limits // empty' 2>/dev/null)
          fi
          if [ -z "$rl" ] && [ -x /usr/bin/plutil ]; then
            rl=$(printf '%s' "$input" | /usr/bin/plutil -extract rate_limits json -o - - 2>/dev/null)
          fi
          case "$rl" in
            '{'*)
              tmp="$out.$$.tmp"
              /bin/mkdir -p "${out%/*}" &&
                printf '{"capturedAt":%s,"rate_limits":%s}\\n' "$(/bin/date +%s)" "$rl" > "$tmp" &&
                /bin/mv -f "$tmp" "$out" || /bin/rm -f "$tmp"
              ;;
          esac
        ) >/dev/null 2>&1 </dev/null
        previous=\(shellQuote(previousCommand ?? ""))
        if [ -n "$previous" ]; then
          printf '%s' "$input" | /bin/sh -c "$previous"
        else
          name=$(printf '%s' "$input" | /usr/bin/plutil -extract model.display_name raw -o - - 2>/dev/null)
          printf '%s' "${name:-Claude Code}"
        fi

        """
    }

    static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\"'\"'") + "'"
    }
}

/// Installs and removes the wrapper in Claude Code's user settings (`~/.claude/settings.json` → `statusLine`).
///
/// - Only the `statusLine` member is touched; the rest of the file is kept byte for byte (text splice + validation).
/// - The file is backed up before every change, and the previous `statusLine` value is stored verbatim so Uninstall
///   puts back exactly what was there (or removes the key if there was none).
/// - The settings file is re-read right before writing; if anything changed meanwhile the write is abandoned.
public struct StatuslineInstaller: Sendable {
    public enum Status: Equatable, Sendable {
        case notInstalled
        case installed
        /// AImana's record exists but `statusLine` no longer runs the wrapper (the user or another tool changed it).
        case replacedElsewhere
    }

    public enum InstallError: Error, Equatable, Sendable {
        case settingsUnreadable
        case concurrentModification
        case notInstalled
        case replacedElsewhere
        case validationFailed
        case writeFailed(String)
    }

    private struct Record: Codable {
        let command: String
        /// The previous `statusLine` value as raw JSON text; nil when there was none.
        let previousStatusLine: String?
        let installedAt: Date
        let backup: String?
    }

    public let settingsFile: URL
    public let supportDirectory: URL
    public let dataFile: URL
    private let clock: @Sendable () -> Date
    /// Test hook: runs between the final re-read decision and the write, to simulate another writer.
    var beforeCommit: (@Sendable () -> Void)?

    public init(settingsFile: URL, supportDirectory: URL, dataFile: URL, clock: @escaping @Sendable () -> Date = { Date() }) {
        self.settingsFile = settingsFile
        self.supportDirectory = supportDirectory
        self.dataFile = dataFile
        self.clock = clock
    }

    public init(paths: RelayPaths) {
        let configDir = paths.environment["CLAUDE_CONFIG_DIR"].flatMap { $0.isEmpty ? nil : $0.split(separator: ",").first }
            .map { URL(fileURLWithPath: String($0)) } ?? paths.home.appendingPathComponent(".claude")
        self.init(settingsFile: configDir.appendingPathComponent("settings.json"),
                  supportDirectory: paths.supportDirectory, dataFile: paths.claudeStatuslineFile)
    }

    public var scriptFile: URL { supportDirectory.appendingPathComponent("statusline.sh") }
    private var recordFile: URL { supportDirectory.appendingPathComponent("statusline-install.json") }
    public var backupDirectory: URL { supportDirectory.appendingPathComponent("backups", isDirectory: true) }

    /// The exact `statusLine.command` the installer writes.
    public var command: String { "/bin/sh " + StatuslineScript.shellQuote(scriptFile.path) }

    public func status() -> Status {
        let current = (try? readSettings()).flatMap { currentCommand(in: $0.editor) }
        if current == command { return .installed }
        return loadRecord() == nil ? .notInstalled : .replacedElsewhere
    }

    /// When the file was last written by the wrapper (i.e. when Claude Code last rendered a statusline).
    public func lastCapture() -> Date? {
        (try? dataFile.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate
    }

    // MARK: Install / uninstall

    public func install() throws {
        let original = try readSettings()
        let previousRaw = original.editor.rawValue("statusLine")
        if currentCommand(in: original.editor) == command {
            // Already installed: refresh the script from the stored record, keep settings as they are.
            let record = loadRecord()
            try writeScript(previousCommand: record?.previousStatusLine.flatMap(Self.command(fromRaw:)))
            return
        }

        var extras: [String: Any] = [:]
        if let previousRaw, let previous = Self.object(fromRaw: previousRaw) {
            extras = previous.filter { $0.key != "type" && $0.key != "command" }
        }
        var editor = original.editor
        do {
            try editor.set("statusLine", rawValue: Self.statusLineJSON(command: command, extras: extras))
        } catch { throw InstallError.validationFailed }
        try validate(editor.text, against: original.text, expectCommand: command)

        try writeScript(previousCommand: previousRaw.flatMap(Self.command(fromRaw:)))
        let backup = try backupSettings(original.data)
        try saveRecord(Record(command: command, previousStatusLine: previousRaw, installedAt: clock(), backup: backup?.path))
        do {
            try commit(editor.text, expecting: original.data)
        } catch {
            try? FileManager.default.removeItem(at: recordFile)
            throw error
        }
    }

    public func uninstall() throws {
        guard let record = loadRecord() else { throw InstallError.notInstalled }
        let original = try readSettings()
        guard currentCommand(in: original.editor) == record.command else { throw InstallError.replacedElsewhere }

        var editor = original.editor
        do {
            if let previous = record.previousStatusLine {
                try editor.set("statusLine", rawValue: previous)
            } else {
                try editor.remove("statusLine")
            }
        } catch { throw InstallError.validationFailed }
        try validate(editor.text, against: original.text, expectCommand: record.previousStatusLine.flatMap(Self.command(fromRaw:)),
                     expectRemoved: record.previousStatusLine == nil)
        _ = try backupSettings(original.data)
        try commit(editor.text, expecting: original.data)
        try? FileManager.default.removeItem(at: recordFile)
        try? FileManager.default.removeItem(at: scriptFile)
    }

    /// Drops AImana's record after the user replaced the statusline themselves. Settings are not touched.
    public func forget() {
        try? FileManager.default.removeItem(at: recordFile)
        try? FileManager.default.removeItem(at: scriptFile)
    }

    // MARK: Helpers

    private struct Settings {
        let data: Data?
        let text: String
        let editor: JSONTopLevelEditor
    }

    private func readSettings() throws -> Settings {
        let target = settingsFile.resolvingSymlinksInPath()
        guard FileManager.default.fileExists(atPath: target.path) else {
            return Settings(data: nil, text: "{}\n", editor: try JSONTopLevelEditor("{}\n"))
        }
        guard let data = try? Data(contentsOf: target), let text = String(data: data, encoding: .utf8),
              (try? JSONSerialization.jsonObject(with: data)) is [String: Any],
              let editor = try? JSONTopLevelEditor(text) else { throw InstallError.settingsUnreadable }
        return Settings(data: data, text: text, editor: editor)
    }

    private func currentCommand(in editor: JSONTopLevelEditor) -> String? {
        editor.rawValue("statusLine").flatMap(Self.command(fromRaw:))
    }

    static func object(fromRaw raw: String) -> [String: Any]? {
        (try? JSONSerialization.jsonObject(with: Data(raw.utf8))) as? [String: Any]
    }

    static func command(fromRaw raw: String) -> String? {
        guard let object = object(fromRaw: raw), let command = object["command"] as? String,
              !command.trimmingCharacters(in: .whitespaces).isEmpty else { return nil }
        return command
    }

    static func statusLineJSON(command: String, extras: [String: Any]) -> String {
        func encode(_ value: Any) -> String {
            (try? JSONSerialization.data(withJSONObject: value, options: [.fragmentsAllowed, .sortedKeys, .withoutEscapingSlashes]))
                .map { String(decoding: $0, as: UTF8.self) } ?? "null"
        }
        var parts = ["\"type\": \"command\"", "\"command\": " + encode(command)]
        for key in extras.keys.sorted() { parts.append(encode(key) + ": " + encode(extras[key]!)) }
        return "{ " + parts.joined(separator: ", ") + " }"
    }

    /// Every member other than `statusLine` must be semantically identical, and `statusLine` must be what we meant.
    private func validate(_ text: String, against originalText: String, expectCommand: String?, expectRemoved: Bool = false) throws {
        guard let new = (try? JSONSerialization.jsonObject(with: Data(text.utf8))) as? [String: Any],
              let old = (try? JSONSerialization.jsonObject(with: Data(originalText.utf8))) as? [String: Any] else {
            throw InstallError.validationFailed
        }
        var newRest = new, oldRest = old
        newRest["statusLine"] = nil
        oldRest["statusLine"] = nil
        guard NSDictionary(dictionary: newRest).isEqual(to: oldRest) else { throw InstallError.validationFailed }
        if expectRemoved {
            guard new["statusLine"] == nil else { throw InstallError.validationFailed }
        } else if let expectCommand {
            guard (new["statusLine"] as? [String: Any])?["command"] as? String == expectCommand else {
                throw InstallError.validationFailed
            }
        }
    }

    private func commit(_ text: String, expecting originalData: Data?) throws {
        beforeCommit?()
        let target = settingsFile.resolvingSymlinksInPath()
        let now = try? Data(contentsOf: target)
        guard now == originalData else { throw InstallError.concurrentModification }
        let attributes = try? FileManager.default.attributesOfItem(atPath: target.path)
        do {
            try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
            try Data(text.utf8).write(to: target, options: .atomic)
        } catch {
            throw InstallError.writeFailed(error.localizedDescription)
        }
        if let permissions = attributes?[.posixPermissions] {
            try? FileManager.default.setAttributes([.posixPermissions: permissions], ofItemAtPath: target.path)
        }
    }

    private func writeScript(previousCommand: String?) throws {
        do {
            try FileManager.default.createDirectory(at: supportDirectory, withIntermediateDirectories: true)
            try Data(StatuslineScript.render(outputFile: dataFile, previousCommand: previousCommand).utf8)
                .write(to: scriptFile, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: scriptFile.path)
        } catch {
            throw InstallError.writeFailed(error.localizedDescription)
        }
    }

    private func backupSettings(_ data: Data?) throws -> URL? {
        guard let data else { return nil }
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyyMMdd-HHmmss"
        var url = backupDirectory.appendingPathComponent("settings-\(f.string(from: clock())).json")
        var n = 1
        while FileManager.default.fileExists(atPath: url.path) {
            url = backupDirectory.appendingPathComponent("settings-\(f.string(from: clock()))-\(n).json")
            n += 1
        }
        do {
            try FileManager.default.createDirectory(at: backupDirectory, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
        } catch {
            throw InstallError.writeFailed(error.localizedDescription)
        }
        return url
    }

    private func loadRecord() -> Record? {
        guard let data = try? Data(contentsOf: recordFile) else { return nil }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return try? decoder.decode(Record.self, from: data)
    }

    private func saveRecord(_ record: Record) throws {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        do {
            try FileManager.default.createDirectory(at: supportDirectory, withIntermediateDirectories: true)
            try encoder.encode(record).write(to: recordFile, options: .atomic)
        } catch {
            throw InstallError.writeFailed(error.localizedDescription)
        }
    }
}
